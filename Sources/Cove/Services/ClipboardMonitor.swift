import AppKit

/// Watches the clipboard for copied text so recent clips can sit on the shelf.
/// Kept in memory only, and skips anything a password manager marks as concealed or transient.
@MainActor
final class ClipboardMonitor {
    var onCopy: ((String) -> Void)?

    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount

    /// Markers from nspasteboard.org that apps (1Password, Bitwarden, Keychain Access…) set on secrets.
    nonisolated static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    func start() {
        guard timer == nil else { return }
        lastChange = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.75, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard let text = Self.clip(from: pasteboard.string(forType: .string), types: types) else { return }
        onCopy?(text)
    }

    /// The text worth keeping from a clipboard change, or nil (secrets, files, blank text).
    nonisolated static func clip(from text: String?, types: Set<String>) -> String? {
        guard types.isDisjoint(with: skippedTypes),
              !types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
              let text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        return text
    }
}
